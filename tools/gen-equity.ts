/**
 * Builds src/poker/preflop-equity.data.ts: all-in preflop equity of every hand class against every other
 * (169 x 169), by Monte Carlo over compatible combo pairs and random boards. Ties count as half.
 *
 *   npm run gen:equity            (about a minute on 4 cores; TRIALS env var sets samples per matchup)
 *
 * The output is committed source data, rebuilt only by hand when this file changes.
 */
import { writeFileSync } from 'node:fs';
import { cpus } from 'node:os';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { CLASS_COMBOS, COMBOS, NUM_CLASSES, rng } from '../src/poker/cards';
import { evaluate } from '../src/poker/eval';

const TRIALS = Number(process.env.TRIALS ?? 12000);

function matchup(i: number, j: number, r: () => number): number {
  const A = CLASS_COMBOS[i]!;
  const B = CLASS_COMBOS[j]!;
  const seven = new Int32Array(7);
  const used = new Uint8Array(52);
  let win = 0;
  let n = 0;
  while (n < TRIALS) {
    const [a1, a2] = COMBOS[A[Math.floor(r() * A.length)]!]!;
    const [b1, b2] = COMBOS[B[Math.floor(r() * B.length)]!]!;
    if (b1 === a1 || b1 === a2 || b2 === a1 || b2 === a2) continue;
    used.fill(0);
    used[a1] = used[a2] = used[b1] = used[b2] = 1;
    for (let k = 2; k < 7; k++) {
      let c: number;
      do c = Math.floor(r() * 52);
      while (used[c]);
      used[c] = 1;
      seven[k] = c;
    }
    seven[0] = a1;
    seven[1] = a2;
    const va = evaluate(seven, 7);
    seven[0] = b1;
    seven[1] = b2;
    const vb = evaluate(seven, 7);
    win += va > vb ? 1 : va === vb ? 0.5 : 0;
    n++;
  }
  return win / n;
}

if (isMainThread) {
  const workers = cpus().length;
  const pairs: [number, number][] = [];
  for (let i = 0; i < NUM_CLASSES; i++) for (let j = i; j < NUM_CLASSES; j++) pairs.push([i, j]);
  const eq = new Float64Array(NUM_CLASSES * NUM_CLASSES);
  let done = 0;
  const started = Date.now();
  await Promise.all(
    Array.from({ length: workers }, (_, w) =>
      new Promise<void>((resolve, reject) => {
        const mine = pairs.filter((_, k) => k % workers === w);
        const worker = new Worker(new URL(import.meta.url), { workerData: { pairs: mine, seed: 1000 + w } });
        worker.on('message', (res: [number, number, number][]) => {
          for (const [i, j, e] of res) {
            eq[i * NUM_CLASSES + j] = e;
            eq[j * NUM_CLASSES + i] = 1 - e;
          }
          done += res.length;
        });
        worker.on('error', reject);
        worker.on('exit', () => resolve());
      }),
    ),
  );
  // A class against itself is exactly 0.5 by symmetry.
  for (let i = 0; i < NUM_CLASSES; i++) eq[i * NUM_CLASSES + i] = 0.5;
  const u16 = new Uint16Array(eq.length);
  eq.forEach((e, k) => (u16[k] = Math.round(e * 65535)));
  const b64 = Buffer.from(u16.buffer).toString('base64');
  writeFileSync(
    'src/poker/preflop-equity.data.ts',
    `// GENERATED by tools/gen-equity.ts (${TRIALS} Monte Carlo trials per matchup). Do not edit by hand.\n` +
      `// 169 x 169 Uint16 little-endian, equity * 65535 of row class vs column class.\n` +
      `export const PREFLOP_EQUITY_B64 = '${b64}';\n`,
  );
  console.log(`gen-equity: ${done} matchups in ${((Date.now() - started) / 1000).toFixed(1)} s`);
} else {
  const { pairs, seed } = workerData as { pairs: [number, number][]; seed: number };
  const r = rng(seed);
  const out: [number, number, number][] = pairs.map(([i, j]) => [i, j, matchup(i, j, r)]);
  parentPort!.postMessage(out);
}
